// Writes src/app/tint-fallbacks.css: see-through colours for browsers without
// CSS color-mix() (Safari before 16.2, Chrome before 111, e.g. iPads stuck on
// iPadOS 15).
//
// Tailwind draws a tint like `bg-red/10` with color-mix(). Where that's
// missing it falls back to the full colour, so red text on a light red tint
// becomes red on solid red: unreadable. This file gives those browsers the same
// tint as a plain rgb() colour, in light and dark.
//
// Run `npm run tint-fallbacks` after using a new tint of one of the colour
// tokens (the build check says when it's needed).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const css = fs.readFileSync(path.join(root, "src/app/globals.css"), "utf8");

// The colour tokens: --name: light-dark(#light, #dark) or a single colour.
const tokens = {};
const rootBlock = css.slice(css.indexOf(":root,"), css.indexOf("}", css.indexOf(":root,")));
for (const m of rootBlock.matchAll(/--([a-z-]+):\s*(light-dark\(\s*(#[0-9a-f]{6})\s*,\s*(#[0-9a-f]{6})\s*\)|(#[0-9a-f]{6}))\s*;/gi)) {
  const [, name, , light, dark, single] = m;
  tokens[name] = { light: light ?? single, dark: dark ?? single };
}

// Every tint of a token used in the app, with its variants (hover:, focus:…).
const PROPERTY = {
  bg: ["background-color"],
  text: ["color"],
  border: ["border-color"],
  ring: ["--tw-ring-color"],
  outline: ["outline-color"],
  from: ["--tw-gradient-from"],
  via: ["--tw-gradient-via"],
  to: ["--tw-gradient-to"],
  fill: ["fill"],
  stroke: ["stroke"],
  divide: ["border-color"],
  placeholder: ["color"],
};
const names = Object.keys(tokens).sort((a, b) => b.length - a.length).join("|");
const used = new Set();
const classRe = new RegExp(`(?<![\\w-])((?:[a-z-]+:)*)(${Object.keys(PROPERTY).join("|")})-(${names})/(\\d{1,3})(?![\\w/-])`, "g");
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p);
    else if (/\.(tsx?|jsx?)$/.test(entry.name)) for (const m of fs.readFileSync(p, "utf8").matchAll(classRe)) used.add(m[0]);
  }
})(path.join(root, "src"));

const rgb = (hex, alpha) => {
  const n = parseInt(hex.slice(1), 16);
  return `rgb(${n >> 16} ${(n >> 8) & 255} ${n & 255} / ${alpha})`;
};
const escape = (cls) => cls.replace(/[:/]/g, (c) => `\\${c}`);
// Tailwind variants, written with @variant so they match Tailwind's own
// (including this app's dark: variant).
const VARIANTS = new Set(["hover", "focus", "focus-visible", "focus-within", "active", "disabled", "dark", "placeholder", "group-hover", "peer-focus", "first", "last"]);

const rules = [];
for (const cls of [...used].sort()) {
  const m = cls.match(new RegExp(`^((?:[a-z-]+:)*)(${Object.keys(PROPERTY).join("|")})-(${names})/(\\d{1,3})$`));
  const [, variantPart, kind, token, amount] = m;
  const variants = variantPart.split(":").filter(Boolean);
  const unknown = variants.find((v) => !VARIANTS.has(v));
  if (unknown) throw new Error(`tint-fallbacks: add support for the "${unknown}:" variant (in ${cls})`);
  const { light, dark } = tokens[token];
  const alpha = Number(amount) / 100;
  const value = light === dark ? rgb(light, alpha) : `light-dark(${rgb(light, alpha)}, ${rgb(dark, alpha)})`;
  let body = PROPERTY[kind].map((prop) => `${prop}: ${value};`).join(" ");
  for (const v of [...variants].reverse()) body = `@variant ${v} { ${body} }`;
  rules.push(`    .${escape(cls)} { ${body} }`);
}

const out = `/* Generated by scripts/tint-fallbacks.mjs (npm run tint-fallbacks). Don't edit by hand.
   See-through colours for browsers without color-mix() (e.g. iPadOS 15), so
   tinted backgrounds don't turn solid and hide the text on them. Newer browsers
   skip this block. */
@layer utilities {
  @supports not (color: color-mix(in lab, red, red)) {
${rules.join("\n")}
  }
}
`;
fs.writeFileSync(path.join(root, "src/app/tint-fallbacks.css"), out);
console.log(`tint-fallbacks: ${rules.length} tints written to src/app/tint-fallbacks.css`);
